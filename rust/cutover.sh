#!/usr/bin/env bash
# Interactive cutover from the PHP OPAC/API to the Rust binary.
#
#   rust/cutover.sh              # print the plan and the config, change nothing
#   rust/cutover.sh --apply      # write the nginx config and reload
#
# The Rust binary is read-only in Phase 1. The PHP app keeps /admin/ and every
# path that is not listed here. Rollback is deleting the config file and
# reloading nginx.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RUST_ADDR="${RUST_ADDR:-127.0.0.1:8080}"
PHP_ADDR="${PHP_ADDR:-127.0.0.1:8881}"
NGINX_CONF="${NGINX_CONF:-/etc/nginx/conf.d/slims9-rust.conf}"
APPLY=0
if [[ "${1:-}" == "--apply" ]]; then
  APPLY=1
fi

if [[ "$APPLY" == 1 && "$(id -u)" != 0 ]]; then
  echo "--apply writes $NGINX_CONF and reloads nginx; run it as root" >&2
  exit 1
fi

echo "SLiMS 9 cutover (Phase 1)"
echo "  Rust   $RUST_ADDR"
echo "  PHP    $PHP_ADDR"
echo "  config $NGINX_CONF"
echo
echo "Paths moved to Rust:"
echo "  /              OPAC home/search/detail (legacy index.php URLs included)"
echo "  /api/          REST API v1 (15 routes)"
echo "  /images/ /css/ /js/ /template/ /static/   static assets"
echo "Paths kept on PHP:"
echo "  /admin/        admin modules (Phases 2-4)"
echo "  /install/      installer"
echo "  /oai.php /oai2.php  OAI-PMH (Phase 5)"
echo

cat <<EOF
# Generated by rust/cutover.sh --apply
upstream slims_rust { server $RUST_ADDR; }
upstream slims_php  { server $PHP_ADDR;  }

server {
    listen 80;
    server_name _;

    location /api/ {
        proxy_pass http://slims_rust;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }

    location ~ ^/(images|css|js|template|static)/ {
        proxy_pass http://slims_rust;
        proxy_set_header Host \$host;
    }

    location ~ ^/(index\.php)?$ {
        proxy_pass http://slims_rust;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }

    location /biblio/ {
        proxy_pass http://slims_rust;
        proxy_set_header Host \$host;
    }

    location /search {
        proxy_pass http://slims_rust;
        proxy_set_header Host \$host;
    }

    # Everything else, including /admin/ and /install/, stays on PHP.
    location / {
        proxy_pass http://slims_php;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF

if [[ "$APPLY" == 0 ]]; then
  echo
  echo "Dry run. Re-run with --apply to write $NGINX_CONF and reload nginx."
  echo "Rollback: rm $NGINX_CONF && nginx -t && systemctl reload nginx"
  exit 0
fi

read -r -p "Write $NGINX_CONF and reload nginx? [y/N] " answer
if [[ "$answer" != "y" && "$answer" != "Y" ]]; then
  echo "aborted; nothing changed"
  exit 0
fi

cat > "$NGINX_CONF" <<EOF
upstream slims_rust { server $RUST_ADDR; }
upstream slims_php  { server $PHP_ADDR;  }

server {
    listen 80;
    server_name _;

    location /api/ {
        proxy_pass http://slims_rust;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }

    location ~ ^/(images|css|js|template|static)/ {
        proxy_pass http://slims_rust;
        proxy_set_header Host \$host;
    }

    location ~ ^/(index\.php)?$ {
        proxy_pass http://slims_rust;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }

    location /biblio/ {
        proxy_pass http://slims_rust;
        proxy_set_header Host \$host;
    }

    location /search {
        proxy_pass http://slims_rust;
        proxy_set_header Host \$host;
    }

    location / {
        proxy_pass http://slims_php;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF

nginx -t
systemctl reload nginx
echo "cutover applied. Verify:"
echo "  curl -fsS http://127.0.0.1/healthz"
echo "  curl -fsS http://127.0.0.1/api/biblio/popular | head -c 200"
echo "Rollback: rm $NGINX_CONF && nginx -t && systemctl reload nginx"
